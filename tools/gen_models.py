"""Generate 1.21.1 LayerDefinitions from the 1.7.10 model geometry reconstructed out of the jar.

Input:  reference/jar/models/Model<Name>.json   (one box per part, verified against the decompiled source)
Output: src/main/java/com/swbr/orespawn/client/model/geom/<Name>Geometry.java

The conventions are verified in docs/research/06-models-design.md: pivots, box origins and sizes
are copied unchanged (both versions use 1/16-block model units, Y-down, pivot Y 24 = ground),
rotations stay in radians with the same Z-Y-X order, and texOffs(u, v) maps face-for-face.

Only geometry is generated. Animation (setupAnim) and render passes are ported by hand in
client/model/<Name>Model.java, which bakes the layer and looks parts up by the constants here.
Generated files are overwritten on every run - never edit them.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "reference" / "jar" / "models"
OUT = ROOT / "src" / "main" / "java" / "com" / "swbr" / "orespawn" / "client" / "model" / "geom"
PACKAGE = "com.swbr.orespawn.client.model.geom"
JAVA_ID = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def f(v: float) -> str:
    """Java float literal that round-trips the value the jar stored (float32)."""
    s = repr(float(v))
    if s.endswith(".0"):
        s = s[:-2]
    return s + "F"


def const_name(part: str) -> str:
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", part)
    return re.sub(r"[^A-Za-z0-9]+", "_", snake).upper()


def generate(model: dict) -> tuple[str, list[str]]:
    warnings = []
    name = model["model"].removeprefix("Model")
    tw, th = model["textureWidth"], model["textureHeight"]
    used, consts, children, hidden = set(), [], [], []
    for p in model["parts"]:
        pname = p.get("name") or f"unnamed_{p['id']}"
        if not JAVA_ID.match(pname):
            warnings.append(f"{model['model']}: part name {pname!r} is not a Java identifier")
        if pname in used:
            warnings.append(f"{model['model']}: duplicate part name {pname}, suffixing id")
            pname = f"{pname}_{p['id']}"
        used.add(pname)
        cname = const_name(pname)
        while cname in {c[0] for c in consts}:
            cname += "_"
        consts.append((cname, pname))
        if p.get("parent"):
            warnings.append(f"{model['model']}: part {pname} has a parent - hierarchy is flattened")
        if not p.get("showModel", True) or p.get("isHidden"):
            hidden.append(cname)
        cubes = "CubeListBuilder.create()"
        for b in p["boxes"]:
            if b.get("inflate"):
                warnings.append(f"{model['model']}: {pname} has inflate {b['inflate']} - ignored")
            if list(b.get("texSize") or [tw, th]) != [tw, th]:
                warnings.append(f"{model['model']}: {pname} box baked with texture size {b['texSize']}, model declares {tw}x{th}")
            if b.get("mirror"):
                cubes += ".mirror()"
            ox, oy, oz = b["origin"]
            w, h, d = b["size"]
            cubes += f".texOffs({b['uv'][0]}, {b['uv'][1]}).addBox({f(ox)}, {f(oy)}, {f(oz)}, {f(w)}, {f(h)}, {f(d)})"
            if b.get("mirror"):
                cubes += ".mirror(false)"
        px, py, pz = p["pivot"]
        rx, ry, rz = p["rotation_rad"]
        if any(p.get("offset") or [0, 0, 0]):
            warnings.append(f"{model['model']}: {pname} has offsetX/Y/Z {p['offset']} - add it in the model class")
        children.append(
            f"        root.addOrReplaceChild({cname}, {cubes},\n"
            f"                PartPose.offsetAndRotation({f(px)}, {f(py)}, {f(pz)}, {f(rx)}, {f(ry)}, {f(rz)}));")

    lines = [
        f"// GENERATED by tools/gen_models.py from reference/jar/models/{model['model']}.json - do not edit.",
        f"package {PACKAGE};",
        "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "",
        "/**",
        f" * Geometry of OreSpawn's {model['model']} ({len(model['parts'])} parts), copied unchanged from the 1.7.10 jar.",
        " * Part order is the order the original constructor created them.",
        " */",
        f"public final class {name}Geometry {{",
        "",
        f"    public static final int TEXTURE_WIDTH = {tw};",
        f"    public static final int TEXTURE_HEIGHT = {th};",
        "",
    ]
    lines += [f"    public static final String {c} = \"{n}\";" for c, n in consts]
    lines += [
        "",
        "    /** Every part in creation order. */",
        "    public static final String[] PARTS = {",
        "            " + ",\n            ".join(c for c, _ in consts),
        "    };",
        "",
        "    /** Parts the original hid at construction time (showModel = false or isHidden = true). */",
        "    public static final String[] HIDDEN = {" + ", ".join(hidden) + "};",
        "",
        f"    private {name}Geometry() {{}}",
        "",
        "    public static LayerDefinition createBodyLayer() {",
        "        MeshDefinition mesh = new MeshDefinition();",
        "        PartDefinition root = mesh.getRoot();",
    ]
    # One statement per part can exceed the 64 KB method limit only far beyond 178 parts; split anyway
    # into chunks so the largest models stay readable in a debugger.
    chunk = 60
    if len(children) <= chunk:
        lines += children
        lines += [f"        return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);", "    }"]
    else:
        groups = [children[i:i + chunk] for i in range(0, len(children), chunk)]
        lines += [f"        addParts{i}(root);" for i in range(len(groups))]
        lines += [f"        return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);", "    }"]
        for i, g in enumerate(groups):
            lines += ["", f"    private static void addParts{i}(PartDefinition root) {{"] + g + ["    }"]
    lines += ["}", ""]
    return "\n".join(lines), warnings


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*Geometry.java"):
        old.unlink()
    all_warn, count, parts = [], 0, 0
    for path in sorted(MODELS.glob("Model*.json")):
        model = json.loads(path.read_text(encoding="utf-8"))
        if model.get("status") != "ok":
            all_warn.append(f"{path.name}: status {model.get('status')} - skipped")
            continue
        java, warn = generate(model)
        name = model["model"].removeprefix("Model")
        (OUT / f"{name}Geometry.java").write_text(java, encoding="utf-8", newline="\n")
        all_warn += warn
        count += 1
        parts += len(model["parts"])
    print(f"generated {count} geometry classes, {parts} parts -> {OUT.relative_to(ROOT)}")
    print(f"warnings: {len(all_warn)}")
    for w in all_warn:
        print("  -", w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
