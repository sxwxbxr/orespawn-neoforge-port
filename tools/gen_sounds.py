"""Generate registry/ModSounds.java from the sound events in docs/catalog/manifest.json.

One SoundEvent per original event, id lowercased (DECISIONS R2). The Java constant keeps the
original event name upper-cased so a port of `worldObj.playSoundAtEntity(this, "orespawn:alo_hurt", ...)`
maps to `ModSounds.ALO_HURT` without a lookup table. Generated - never edit by hand.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "main" / "java" / "com" / "swbr" / "orespawn" / "registry" / "ModSounds.java"


def const(event: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", event)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).upper()


def main() -> int:
    manifest = json.loads((ROOT / "docs" / "catalog" / "manifest.json").read_text(encoding="utf-8"))
    seen = {}
    fields = []
    for s in sorted(manifest["sounds"], key=lambda s: s["id"]):
        c = const(s["legacy_event"])
        if c in seen:
            print(f"constant collision: {c} for {s['legacy_event']} and {seen[c]}")
            return 1
        seen[c] = s["legacy_event"]
        users = ", ".join(s.get("referenced_by") or []) or "no class reference found"
        fields.append(f"    /** {s['legacy_event']} - {users} */\n"
                      f"    public static final DeferredHolder<SoundEvent, SoundEvent> {c} = register(\"{s['id']}\");")
    java = "\n".join([
        "// GENERATED by tools/gen_sounds.py from docs/catalog/manifest.json - do not edit.",
        "package com.swbr.orespawn.registry;",
        "",
        "import com.swbr.orespawn.OreSpawn;",
        "import net.minecraft.core.registries.Registries;",
        "import net.minecraft.resources.ResourceLocation;",
        "import net.minecraft.sounds.SoundEvent;",
        "import net.neoforged.neoforge.registries.DeferredHolder;",
        "import net.neoforged.neoforge.registries.DeferredRegister;",
        "",
        "/** Every sound event of the original mod, ids lowercased. */",
        "public final class ModSounds {",
        "",
        "    public static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(Registries.SOUND_EVENT, OreSpawn.MOD_ID);",
        "",
        *fields,
        "",
        "    private ModSounds() {}",
        "",
        "    private static DeferredHolder<SoundEvent, SoundEvent> register(String id) {",
        "        return SOUNDS.register(id, () -> SoundEvent.createVariableRangeEvent(",
        "                ResourceLocation.fromNamespaceAndPath(OreSpawn.MOD_ID, id)));",
        "    }",
        "",
        "    /** Loads this class so every holder above is registered. */",
        "    public static void init() {}",
        "}",
        "",
    ])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(java, encoding="utf-8", newline="\n")
    print(f"generated {len(fields)} sound events -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
